// Embed the checked-in mobile atlas; optionally regenerate it from a full 4x4 sheet.
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'assets/effects');
const names=['fire','frost','vine','holy','time','wind','earth','shield','explosion','shatter','arcane','dust','heal','blessing','summon','lightning'];
(async()=>{
 if(process.argv[2]){
  const sharp=require('sharp'),src=path.resolve(process.argv[2]),m=await sharp(src).metadata();
  if(m.width!==m.height)throw Error('Expected a square 4x4 effect sheet');
  await sharp(src).resize(384,384).webp({quality:65,alphaQuality:45,effort:6}).toFile(path.join(dir,'atlas.webp'));
 }
 const meta={columns:4,cell:96,names,source:'Mobile 4x4 atlas derived from the user-supplied transparent 1254px sheet. Full-resolution original preserved in the delivered backup.'};
 fs.writeFileSync(path.join(dir,'manifest.json'),JSON.stringify(meta,null,2)+'\n');
 fs.writeFileSync(path.join(root,'src/effect-data.js'),'/* Generated by node dev/pack-effects.cjs */\nconst EFFECT_DATA='+JSON.stringify({...meta,url:'data:image/webp;base64,'+fs.readFileSync(path.join(dir,'atlas.webp')).toString('base64')})+';\n');
 console.log('Embedded mobile atlas; original sheet is not required for normal builds.');
})().catch(e=>{console.error(e);process.exit(1)});
