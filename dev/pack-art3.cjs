const fs=require('fs'),path=require('path'),root=path.resolve(__dirname,'..');
const meta=JSON.parse(fs.readFileSync(path.join(root,'assets/art3/manifest.json'),'utf8'));
const images=Object.fromEntries(['pets','world','effects','portraits'].map(name=>[name,'data:image/webp;base64,'+fs.readFileSync(path.join(root,'assets/art3',name+'.webp')).toString('base64')]));
fs.writeFileSync(path.join(root,'src/art3-data.js'),'/* Generated by node dev/pack-art3.cjs */\nconst ART3_DATA = '+JSON.stringify({images,meta})+';\n');
console.log('Packed four shared art3 atlases.');
