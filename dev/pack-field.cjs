const fs=require('fs'),path=require('path'),sharp=require('sharp'),crypto=require('crypto');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'assets/field1');
(async()=>{
 fs.mkdirSync(dir,{recursive:true});
 if(process.argv[2]&&process.argv[3]){
  const ground=process.argv[2],props=process.argv[3];
  await sharp(ground).resize(512,512).webp({quality:82}).toFile(path.join(dir,'meadow.webp'));
  const {data,info}=await sharp(props).ensureAlpha().raw().toBuffer({resolveWithObject:true}),cells=[],frames=[];
  const sw=Math.floor(info.width/2),sh=Math.floor(info.height/2),names=['grass','stones','drygrass','flowers'];
  for(let i=0;i<4;i++){
   const ox=i%2*sw,oy=Math.floor(i/2)*sh;let l=sw,t=sh,r=-1,b=-1;
   for(let y=0;y<sh;y++)for(let x=0;x<sw;x++)if(data[((oy+y)*info.width+ox+x)*4+3]>12){l=Math.min(l,x);t=Math.min(t,y);r=Math.max(r,x);b=Math.max(b,y);}
   if(r<l||l===0||t===0||r===sw-1||b===sh-1)throw Error('Missing/cropped alpha sprite '+names[i]);
   const w=r-l+1,h=b-t+1,k=Math.min(112/w,112/h),dw=Math.round(w*k),dh=Math.round(h*k),left=i%2*128+Math.floor((128-dw)/2),top=Math.floor(i/2)*128+120-dh;
   const image=await sharp(props).extract({left:ox+l,top:oy+t,width:w,height:h}).resize(dw,dh).png().toBuffer();cells.push({input:image,left,top});
   frames.push({name:names[i],x:left,y:top,w:dw,h:dh,source:{x:ox+l,y:oy+t,w,h}});
  }
  await sharp({create:{width:256,height:256,channels:4,background:'#00000000'}}).composite(cells).webp({quality:86,alphaQuality:100}).toFile(path.join(dir,'props.webp'));
  const sha=p=>crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
  fs.writeFileSync(path.join(dir,'manifest.json'),JSON.stringify({version:'0.40-field1',frames,sources:{ground:{file:'meadow-source.png',sha256:sha(ground)},props:{file:'props-source.png',sha256:sha(props)}},note:'Full generated PNG sources preserved in workspace art-originals/field1. Optimization/cropping only; genuine alpha preserved.'},null,2)+'\n');
 }
 const meta=JSON.parse(fs.readFileSync(path.join(dir,'manifest.json'),'utf8'));
 const images=Object.fromEntries(['meadow','props'].map(n=>[n,'data:image/webp;base64,'+fs.readFileSync(path.join(dir,n+'.webp')).toString('base64')]));
 fs.writeFileSync(path.join(root,'src/field-data.js'),'/* Generated by node dev/pack-field.cjs */\nconst FIELD_DATA='+JSON.stringify({images,meta})+';\n');
 console.log('Packed meadow and four transparent props.');
})().catch(e=>{console.error(e);process.exit(1)});
