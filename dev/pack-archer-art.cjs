const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'assets/archer-art6');
const images = Object.fromEntries(fs.readdirSync(dir).filter(name => name.endsWith('.webp')).sort().map(name => [
  path.basename(name, '.webp'),
  'data:image/webp;base64,' + fs.readFileSync(path.join(dir, name)).toString('base64'),
]));
fs.writeFileSync(path.join(root, 'src/archer-art-data.js'), '/* Generated by dev/pack-archer-art.cjs */\nconst ARCHER_ART_DATA = ' + JSON.stringify(images, null, 2) + ';\n');
